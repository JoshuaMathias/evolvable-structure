"""Generate the repository's GitHub wiki from docs/, so the docs stay the one source and the wiki cannot drift.

    python scripts/docs_to_wiki.py --out <wiki checkout>           write the pages (replacing every page there)
    python scripts/docs_to_wiki.py --out <folder> --check          also fail when a page is missing from the start page

docs/README.md becomes Home, and its headings and links, in order, become the sidebar, so the start page is the one place
the reading order is curated. Every markdown file under docs/ becomes a page named after its first heading, plus the
extra pages in EXTRA_PAGES. A link to another page becomes a wiki link; a link to anything else in the repository
becomes a link to that file on GitHub. Each page ends with a note naming the file it was generated from.
"""
from __future__ import annotations

import argparse
import posixpath
import re
import sys
from pathlib import Path
from typing import Dict, List, Tuple

REPO_URL = "https://github.com/JoshuaMathias/evolvable-structure"
BRANCH = "main"
HOME_SOURCE = "docs/README.md"
EXTRA_PAGES = ["skill/evolvable-structure/steps.md"]
LINK = re.compile(r"(!?)\[([^\]]*)\]\(([^)\s]+)\)")
HEADING = re.compile(r"^(#{1,6})\s+(.*)$", re.M)


def page_name(title: str) -> str:
    """A short wiki page name from a heading: the text before a colon or comma, with "(... template)" as a prefix."""
    template = re.search(r"\(([\w ]*)template\)\s*$", title)
    if template:
        title = "Template " + title[: template.start()].strip()
    title = re.split(r"[:,]", title, maxsplit=1)[0]
    title = re.sub(r"[^\w\s-]", "", title).strip()
    return re.sub(r"\s+", "-", title)


def collect_pages(root: Path) -> Dict[str, str]:
    """Map each source path (relative, posix) to its wiki page name."""
    sources = sorted(p.relative_to(root).as_posix() for p in (root / "docs").rglob("*.md")) + EXTRA_PAGES
    pages: Dict[str, str] = {}
    for rel in sources:
        if rel == HOME_SOURCE:
            pages[rel] = "Home"
            continue
        first = HEADING.search((root / rel).read_text(encoding="utf-8"))
        name = page_name(first.group(2)) if first else page_name(Path(rel).stem.replace("-", " ").title())
        if name in pages.values():
            raise SystemExit(f"two pages would be named {name}; change one heading ({rel})")
        pages[rel] = name
    return pages


def rewrite_links(text: str, source: str, pages: Dict[str, str], root: Path) -> str:
    """Point each relative link at a wiki page when the target is one, else at the file on GitHub."""
    def replace(match: re.Match) -> str:
        bang, label, target = match.groups()
        if re.match(r"^(?:[a-z]+:|#)", target):
            return match.group(0)
        path, _, fragment = target.partition("#")
        resolved = posixpath.normpath(posixpath.join(posixpath.dirname(source), path))
        anchor = f"#{fragment}" if fragment else ""
        if resolved in pages and not bang:
            return f"[{label}]({pages[resolved]}{anchor})"
        readme = posixpath.join(resolved, "README.md")
        if readme in pages and not bang:
            return f"[{label}]({pages[readme]}{anchor})"
        kind = "tree" if (root / resolved).is_dir() else ("raw" if bang else "blob")
        return f"{bang}[{label}]({REPO_URL}/{kind}/{BRANCH}/{resolved}{anchor})"
    return LINK.sub(replace, text)


def strip_generated_comment(text: str) -> str:
    """Drop a leading 'Generated by ... Do not edit.' HTML comment: on the wiki the footer says where to edit."""
    return re.sub(r"\A<!--.*?-->\s*", "", text, flags=re.S)


def sidebar(home_text: str, source: str, pages: Dict[str, str]) -> Tuple[str, List[str]]:
    """The sidebar from the start page's headings and links, in order, and the pages it reaches."""
    lines: List[str] = ["**[Home](Home)**"]
    reached: List[str] = ["Home"]
    for line in home_text.splitlines():
        heading = re.match(r"^##\s+(.*)$", line)
        if heading:
            if heading.group(1).strip().lower().startswith("about"):
                break
            lines += ["", f"**{heading.group(1).strip()}**", ""]
            continue
        for _, label, target in LINK.findall(line):
            if re.match(r"^(?:[a-z]+:|#)", target):
                continue
            resolved = posixpath.normpath(posixpath.join(posixpath.dirname(source), target.split("#")[0]))
            name = pages.get(resolved)
            if name:
                reached.append(name)
                lines.append(f"- [{label}]({name})")
    return "\n".join(lines).strip() + "\n", reached


def build(root: Path, out: Path, check: bool) -> int:
    """Write every page, Home and the sidebar into out, replacing the pages already there."""
    pages = collect_pages(root)
    out.mkdir(parents=True, exist_ok=True)
    for old in out.glob("*.md"):
        old.unlink()
    for rel, name in pages.items():
        text = strip_generated_comment((root / rel).read_text(encoding="utf-8"))
        body = rewrite_links(text, rel, pages, root).rstrip() + "\n"
        footer = (f"\n---\n*Generated from [{rel}]({REPO_URL}/blob/{BRANCH}/{rel}) in the repository. "
                  "Edit it there: changes made on the wiki are replaced.*\n")
        (out / f"{name}.md").write_text(body + footer, encoding="utf-8")
    side, reached = sidebar((root / HOME_SOURCE).read_text(encoding="utf-8"), HOME_SOURCE, pages)
    (out / "_Sidebar.md").write_text(side, encoding="utf-8")
    missing = sorted(set(pages.values()) - set(reached))
    print(f"wrote {len(pages)} page(s) and the sidebar to {out}")
    if missing:
        print("not linked from the start page (so not in the sidebar): " + ", ".join(missing))
    return 1 if check and missing else 0


def main(argv: List[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True, help="the wiki checkout (or any folder) to write into")
    parser.add_argument("--root", default=str(Path(__file__).resolve().parent.parent), help="the repository root")
    parser.add_argument("--check", action="store_true", help="fail when a page is not linked from the start page")
    args = parser.parse_args(argv)
    return build(Path(args.root), Path(args.out), args.check)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
