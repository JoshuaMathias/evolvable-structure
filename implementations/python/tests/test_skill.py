"""The public copy of a skill: generated from a source folder, checked for staleness and leaks, and installed."""
from pathlib import Path

import pytest

from esoi import cli, config, skill

FRONT = "---\nname: demo\ndescription: d\n---\n"
SKILL_TEXT = FRONT + "\n# demo\n\nKeep notes in this skill's folder under /home/user/skills/demo (only here, for ann).\n"
TABLE = {"dir": "copy", "copies": ["bundle"], "include": ["SKILL.md", "notes/*.md"], "private_dirs": ["archive"],
         "substitute": [{"file": "SKILL.md", "pattern": r" under \S+ \(only here[^)]*\)", "replacement": "", "reason": "a machine folder"}]}


@pytest.fixture
def world(tmp_path):
    src = tmp_path / "src"
    (src / "notes").mkdir(parents=True)
    (src / "SKILL.md").write_text(SKILL_TEXT)
    (src / "notes" / "a.md").write_text("# a\nOpen it.<!--private (`corpus.md > 7`)-->\n<!--private one\ntwo-->\nEnd.\n")
    (src / "secret.md").write_text("not included\n")
    root = tmp_path / "repo"
    root.mkdir()
    return root, src, config.Config(root=root, skill=dict(TABLE))


def say_into(lines):
    return lines.append


def test_strip_private_removes_spans_and_the_lines_they_leave_empty():
    text = "a <!--private x--> b\nc.<!--private y-->\n<!--private z\nw-->\nd (<!--private p-->)\n"
    assert skill.strip_private(text) == "a b\nc.\nd ()\n"


def test_strip_private_joins_a_sentence_ended_by_a_marker_line():
    assert skill.strip_private("see it\n<!--private (`x.md > y`)-->.\nNext") == "see it.\nNext"


def test_the_notice_goes_in_a_comment_after_the_frontmatter_and_the_substitution_is_the_only_edit(world):
    root, src, cfg = world
    copy = skill.build_copy(src, skill.settings_from(cfg))
    assert sorted(copy) == ["SKILL.md", "notes/a.md"]
    shipped = copy["SKILL.md"]
    assert shipped.startswith(FRONT + "<!-- Generated by `esoi skill sync`")
    body = shipped.split("-->\n", 1)[1]
    assert body == SKILL_TEXT[len(FRONT):].replace(" under /home/user/skills/demo (only here, for ann)", "")
    assert copy["notes/a.md"] == "# a\nOpen it.\nEnd.\n"


def test_a_substitution_must_match_exactly_once(world):
    root, src, cfg = world
    (src / "SKILL.md").write_text(FRONT + "\nNothing to replace.\n")
    with pytest.raises(skill.SkillError, match="matched 0 time"):
        skill.build_copy(src, skill.settings_from(cfg))


def test_an_include_pattern_that_matches_nothing_is_an_error(world):
    root, src, cfg = world
    cfg.skill["include"] = ["SKILL.md", "gone/*.md"]
    with pytest.raises(skill.SkillError, match="matches no file"):
        skill.build_copy(src, skill.settings_from(cfg))


def test_sync_writes_every_copy_and_check_passes(world):
    root, src, cfg = world
    lines = []
    assert skill.sync(cfg, str(src), say=lines.append) == 0
    assert (root / "copy" / "notes" / "a.md").read_text() == (root / "bundle" / "notes" / "a.md").read_text()
    assert skill.sync(cfg, str(src), check=True, say=lines.append) == 0
    assert skill.check(cfg, str(src), say=lines.append) == 0


@pytest.mark.parametrize("damage", ["source", "copy", "extra", "missing", "bundle"])
def test_drift_is_found(world, damage):
    root, src, cfg = world
    skill.sync(cfg, str(src), say=lambda text: None)
    if damage == "source":
        (src / "SKILL.md").write_text(SKILL_TEXT + "New.\n")
    elif damage == "copy":
        (root / "copy" / "SKILL.md").write_text("edited\n")
    elif damage == "extra":
        (root / "copy" / "extra.md").write_text("x\n")
    elif damage == "missing":
        (root / "copy" / "notes" / "a.md").unlink()
    else:
        (root / "bundle" / "SKILL.md").write_text("edited\n")
    lines = []
    assert skill.check(cfg, str(src), say=lines.append) == 1
    assert skill.sync(cfg, str(src), check=True, say=lines.append) == 1


def test_a_missing_source_is_reported_not_guessed(world, monkeypatch):
    root, src, cfg = world
    monkeypatch.delenv(skill.SOURCE_ENV, raising=False)
    lines = []
    assert skill.sync(cfg, None, say=lines.append) == 2 and "not found" in lines[0]


def test_check_without_the_source_still_scans_the_committed_copy(world, monkeypatch):
    root, src, cfg = world
    monkeypatch.delenv(skill.SOURCE_ENV, raising=False)
    skill.sync(cfg, str(src), say=lambda text: None)
    lines = []
    assert skill.check(cfg, None, say=lines.append) == 0 and any("not reachable" in line for line in lines)
    (root / "copy" / "notes" / "a.md").write_text("Mail ann@corp.example\n")
    (root / "bundle" / "notes" / "a.md").write_text("Mail ann@corp.example\n")
    assert skill.check(cfg, None, say=lines.append) == 1


def test_scan_finds_each_kind_of_leak():
    files = {"SKILL.md": "See `INDEX.md > x`. Path /home/user/x and ann@corp.example.\n",
             "INDEX.md": "<!--private x--> `corpus.md > 7` `coding/gone.md` `archive/old.md` Built on Secretlib\n",
             "coding/here.md": "ok\n"}
    terms = [("secretlib", skill.re.compile("secretlib", skill.re.I))]
    kinds = sorted({f.kind for f in skill.scan(files, terms, ["archive"])})
    assert kinds == ["absolute-path", "denied-term", "email", "pointer-to-unshipped-note", "private-marker",
                     "reference-to-a-file-not-shipped"]


def test_scan_accepts_pointers_and_references_inside_the_copy_and_home_placeholders():
    files = {"SKILL.md": "Install to ~/.claude/skills/x. See `INDEX.md > a` and `sub/b.md`.\n", "INDEX.md": "x\n",
             "sub/b.md": "Back to `../INDEX.md > a` and `../sub/b.md`.\n"}
    assert skill.scan(files) == []


def test_the_deny_list_is_read_from_a_file_and_not_from_the_configuration(tmp_path, monkeypatch):
    file = tmp_path / "deny.txt"
    file.write_text("# comment\n\nsecretlib\nre:\\bzed\\b\n")
    monkeypatch.setenv(skill.DENYLIST_ENV, str(file))
    terms = skill.load_denylist(None)
    assert [t for t, _ in terms] == ["secretlib", "re:\\bzed\\b"]
    assert terms[1][1].search("thanks, ZED.") and not terms[1][1].search("zedx")
    with pytest.raises(skill.SkillError):
        skill.load_denylist(str(tmp_path / "missing.txt"))


def test_install_into_the_user_a_project_or_another_agent(tmp_path, monkeypatch):
    bundled = tmp_path / "pkg" / "evolvable-structure"
    bundled.mkdir(parents=True)
    (bundled / "SKILL.md").write_text(FRONT + "body\n")
    monkeypatch.setenv("HOME", str(tmp_path / "home"))
    say = []
    assert skill.install(source=str(bundled), say=say.append) == 0
    assert (tmp_path / "home" / ".claude" / "skills" / "evolvable-structure" / "SKILL.md").is_file()
    assert skill.install(project=str(tmp_path / "proj"), source=str(bundled), say=say.append) == 0
    assert (tmp_path / "proj" / ".claude" / "skills" / "evolvable-structure" / "SKILL.md").is_file()
    assert skill.install(dest=str(tmp_path / "agent"), source=str(bundled), say=say.append) == 0
    assert (tmp_path / "agent" / "evolvable-structure" / "SKILL.md").is_file()
    assert skill.install(source=str(bundled), say=say.append) == 0 and "already installed" in say[-1]


def test_install_does_not_replace_a_different_skill_without_force(tmp_path, monkeypatch):
    bundled = tmp_path / "pkg" / "evolvable-structure"
    bundled.mkdir(parents=True)
    (bundled / "SKILL.md").write_text("new\n")
    target = tmp_path / "agent" / "evolvable-structure"
    target.mkdir(parents=True)
    (target / "SKILL.md").write_text("mine\n")
    say = []
    assert skill.install(dest=str(tmp_path / "agent"), source=str(bundled), say=say.append) == 1
    assert (target / "SKILL.md").read_text() == "mine\n"
    assert skill.install(dest=str(tmp_path / "agent"), source=str(bundled), force=True, say=say.append) == 0
    assert (target / "SKILL.md").read_text() == "new\n"


def test_the_command_installs_without_any_configuration(tmp_path, monkeypatch, capsys):
    monkeypatch.chdir(tmp_path)
    assert cli.main(["skill", "install", "--dest", str(tmp_path / "skills")]) == 0
    assert (tmp_path / "skills" / "evolvable-structure" / "SKILL.md").is_file()


def test_the_settings_reject_unknown_and_missing_keys():
    with pytest.raises(skill.SkillError):
        skill.settings_from(config.Config(root=Path("."), skill={}))
    with pytest.raises(skill.SkillError, match="unknown"):
        skill.settings_from(config.Config(root=Path("."), skill={"dir": "a", "include": ["x"], "colour": 1}))
    with pytest.raises(skill.SkillError, match="reason"):
        skill.settings_from(config.Config(root=Path("."), skill={"dir": "a", "include": ["x"], "substitute": [{"file": "x", "pattern": "p", "replacement": ""}]}))


REPO = Path(__file__).resolve().parents[3]


@pytest.mark.skipif(not (REPO / "esoi.toml").exists(), reason="not run from a checkout of the repository")
def test_the_published_copies_agree_and_hold_no_generic_leak():
    cfg = config.load(REPO)
    settings = skill.settings_from(cfg)
    primary = skill.read_copy(REPO / settings.dir)
    assert primary and skill.scan(primary, private_dirs=settings.private_dirs) == []
    for other in settings.copies:
        assert skill.differences(primary, skill.read_copy(REPO / other)) == []


def test_the_bundled_copy_is_what_install_uses():
    assert (skill.BUNDLED / "evolvable-structure" / "SKILL.md").is_file()
