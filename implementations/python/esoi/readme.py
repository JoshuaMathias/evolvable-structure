"""A readable README.md for every intent folder, generated from its records.

The CSV files hold the specification; a person or an agent opening the folder should not need to open five of them to
learn what it is. ``render`` writes the page from the records of one intent (its problems, solutions,
implementations, ideals and metrics), so the page cannot disagree with them and nothing in it is kept by hand: it is
regenerated by ``esoi check --write-docs`` and rule S8 reports it when out of date. Prose a person wrote about the
network (a ``network.md``) is theirs and is left alone.
"""
from __future__ import annotations

from typing import Dict, List

from .intents import Intent
from .registry import Registry

FIRST_LINE = ("These are ESOI records (evolvable structure that optimizes intent): why {subject} exists, and its problems, "
              "solutions, implementations, ideals and metrics. This page is generated from the CSV files beside it by "
              "`esoi check --write-docs`; edit the CSV files, not this page.")


def one_line(text: str) -> str:
    return " ".join((text or "").split()).replace("|", "/")


def mine(rows: List[Dict[str, str]], intent_id: str) -> List[Dict[str, str]]:
    return [r for r in rows if r.get("intent_id", intent_id) == intent_id]


def render(registry: Registry, intent: Intent) -> str:
    """The README of one intent folder."""
    iid = intent.intent_id
    name = one_line(intent.row.get("name", "")) or iid
    lines = [FIRST_LINE.format(subject="this project" if intent.is_top else "this sub-intent"), "", f"# {name}", ""]
    if intent.row.get("vision_statement", "").strip():
        lines += [one_line(intent.row["vision_statement"]), ""]
    if not intent.is_top:
        lines += [f"This sub-intent arises as the implementation `{intent.row.get('implements', '')}` of its parent "
                  f"intent `{intent.parent}`. Opportunity: {one_line(intent.row.get('opportunity', ''))}", ""]
    problems = mine(registry.problems, iid)
    if problems:
        lines += ["## Problems", ""] + [f"- `{r.get('problem_id', '')}`: {one_line(r.get('problem', ''))}" for r in problems] + [""]
    ideals = mine(registry.ideals, iid)
    if ideals:
        lines += ["## Ideals", ""] + [f"- `{r.get('ideal_id', '')}`, {one_line(r.get('name', ''))}: {one_line(r.get('principle', ''))}"
                                      for r in ideals] + [""]
    solutions = mine(registry.every_solution(), iid)
    if solutions:
        lines += ["## Solutions", "", "| Solution | Name | Selected | Metric |", "|---|---|---|---|"]
        lines += [f"| `{r.get('solution_id', '')}` | {one_line(r.get('name', ''))} | {one_line(r.get('selected', ''))} | "
                  f"{one_line(r.get('metric', '')) or 'none yet'} |" for r in solutions] + [""]
    implementations = mine(registry.implementations, iid)
    if implementations:
        lines += ["## Implementations", "", "| Implementation | Name | Where | Sub-intent |", "|---|---|---|---|"]
        lines += [f"| `{r.get('implementation_id', '')}` | {one_line(r.get('name', ''))} | {one_line(r.get('path', ''))} | "
                  f"{('[' + r['sub_intent'] + '](' + r['sub_intent'] + '/README.md)') if r.get('sub_intent') else ''} |"
                  for r in implementations] + [""]
    metrics = mine(registry.metrics, iid)
    if metrics:
        lines += ["## Metrics", ""] + [f"- `{r.get('metric_id', '')}`, {one_line(r.get('name', ''))}: "
                                       f"`{one_line(r.get('command', '')) or 'none'}`" for r in metrics] + [""]
    return "\n".join(lines).rstrip() + "\n"
