def standard_template(rows: List[Dict[str, str]]) -> str:
    head = f"""<!-- {ATTRIBUTION} The sections around the generated field list are a skeleton to adapt. -->

# The standard for applying ESOI in this repository (template)

One solution id names every part of one idea. Nothing in the repository exists outside a solution, and a solution is
not done until a recorded run says how well it works. This page is enough to add a solution; the numbered rules that
enforce it are a reference.

## Intents

- **The top intent** (write this first): why the project exists, in its own words: `intent.csv` with its name and
  vision statement, then its problems, ideals, metrics and solutions. It has a single top solution, which the
  project's other solutions serve through its implementation (`uses_solution_ids`). The evolvable structure the
  project applies is one of those other solutions, not the top. The top intent need not sit in the top folder. The
  folder that holds it: <!-- path -->.
- **Sub-intents**: a subfolder named by its `intent_id`, with its own `intent.csv`, only where it brings insights on
  opportunities that do not emerge directly from the parent intent or the solution it implements. It arises as an
  implementation of a solution in the parent intent and says which in `implements`.
- **Solutions** are recorded in the intent they serve; an implementation that builds on solutions of other intents lists
  them in `uses_solution_ids`.
- **Folders** are how this layout carries intents: it is the selected implementation of the `intent-registry` solution,
  and its rival, records kept beside the code they describe, stays a listed alternative.

## The shape of one solution

| Part | Where | Holds |
|---|---|---|
| Row | <!-- path to solutions.csv --> | the solution's template fields, its links, its implementations, the selected one and why, the kind of metric |
| Evaluation | <!-- path --> | cases, a scorer and an implementation file per alternative that runs the real thing |
| Result | <!-- path to results.csv --> | one row per recorded run, with the commit and the hash of the cases |
| Decision | the leaderboard | the winner on the same cases, or a stated tie |
| Place | <!-- path to components.csv --> | which files serve which solution |

## Eval or invariant

Whether "best" can vary decides the kind. An **eval** solution has implementations that differ on the metric, so they
are ranked on the same cases. An **invariant** solution is a rule that holds or does not; it keeps its cases and a
recorded run, is never ranked, and keeps a deliberately naive baseline that its cases must fail.

## Adding a solution

1. Write the record (every template field).
2. Write the cases and one implementation per alternative.
3. Record a run per implementation on committed code.
4. Place the files in a component that lists the solution.
5. Run the checks; fix what they name, or record a waiver with a reason.

## Record fields (generated)

"""
    return head + render_section(rows) + "\n"


def review_sheet(rows: List[Dict[str, str]]) -> str:
    template: Dict[str, List[Dict[str, str]]] = {}
    for row in rows:
        template.setdefault(row["entity"], []).append(row)
    cols = columns(template)
    out = [f"<!-- {ATTRIBUTION} -->", "", "# Review sheet layout", "",
           "One spreadsheet tab per intent type, so a person can review problems, ideals, solutions, implementations "
           "and metrics, with the latest verdict, without reading code. Structural columns are generated from the "
           "records and never edited in the sheet; the four `tracking_*` columns are the reviewers' own and are kept "
           "when the sheet is rebuilt. A blank `tracking_status` means \"use `auto_status`\".", ""]
    for tab, names in cols.items():
        out += [f"## {tab}", "", "| Column | Kind |", "|---|---|"]
        for name in names:
            out.append(f"| `{name}` | {'generated' if name != names[0] else 'key'} |")
        for name in TRACKING:
            out.append(f"| `{name}` | reviewer |")
        out.append("")
    return "\n".join(out)


def record_headers(rows: List[Dict[str, str]]) -> Dict[str, str]:
    template: Dict[str, List[Dict[str, str]]] = {}
    for row in rows:
        template.setdefault(row["entity"], []).append(row)
    out: Dict[str, str] = {}
    for entity, (name, key) in FILES.items():
        fields = [r["field_key"] for r in template.get(entity, []) if r["group"] in ("specify", "interface")]
        cols = [key] + fields + LINKS[entity] + PARENT_CELLS[entity]
        if entity == "implementation":
            cols = [key, "solution_id", "filepath"] + fields + PARENT_CELLS[entity]
        out[name] = ",".join(dict.fromkeys(cols)) + "\n"
    intent_fields = [r["field_key"] for r in template.get("intent", []) if r["group"] in ("specify", "interface")]
    out["intent.csv"] = ",".join(["intent_id"] + intent_fields + INTENT_COLUMNS[1:]) + "\n"
    out["components.csv"] = "component_id,layer,path,role,solutions\n"
    out["waivers.csv"] = "rule,path,reason\n"
    out["metric_runs.csv"] = ",".join(RUN_TABLE_COLUMNS) + "\n"
    out["results.csv"] = ("date,component,impl,cases,passed,dev,heldout,model_calls,tokens_in,tokens_out,cost_usd,"
                          "seconds,git_sha,cases_sha,model,details\n")
    return out


def section(text: str, heading: str) -> str:
    match = re.search(rf"^## {re.escape(heading)}[^\n]*\n(.*?)(?=^## |\Z)", text, re.M | re.S)
    return match.group(1).strip("\n") if match else ""


def excerpts(skill_text: str) -> str:
    """The skill's opening, first purpose paragraph, definitions and principles, verbatim and attributed."""
    body = re.sub(r"\A---\n.*?\n---\n", "", skill_text, flags=re.S)
    opening = re.split(r"^## ", body, maxsplit=1, flags=re.M)[0]
    opening = re.sub(r"^# .*\n", "", opening.strip() + "\n", count=1, flags=re.M).strip()
    purpose = section(body, "Purpose").split("\n\n")[0]
    definitions = section(body, "Definitions")
    for marker in ("Intent specification:", "Intent template definitions"):
        definitions = definitions.split(marker)[0]
    definitions = definitions.strip()
    principles = section(body, "Principles")
    parts = ["<!-- Generated by `esoi template sync` from the evolvable-structure skill's `SKILL.md`. Do not edit. -->", "",
             "# The definitions and principles, in Joshua Mathias's words", "",
             "Everything below is quoted verbatim from the evolvable-structure skill's `SKILL.md`, written by Joshua "
             "Mathias, who is its authority. It is regenerated whenever that file changes. The intent template itself "
             "(Intent, Problem, Solution, Implementation, Ideal, Metric) is in [the templates](../templates/).", "",
             "## What it is", "", quote(opening), "", "## Purpose", "", quote(purpose), "", "## Definitions", "",
             quote(definitions), "", "## Principles (ideals)", "", quote(principles), ""]
    return "\n".join(parts)


def quote(text: str) -> str:
    return "\n".join(("> " + line) if line.strip() else ">" for line in text.splitlines())


def generated_files(rows: List[Dict[str, str]], skill_text: str, config: Config) -> Dict[Path, str]:
    """Every generated file, by absolute path, for the configured outputs."""
    files: Dict[Path, str] = {}
    entities = by_entity(rows)
    if config.templates_dir:
        folder = config.root / config.templates_dir
        for entity in ENTITIES:
            if entity in entities:
                files[folder / f"{entity}.md"] = entity_template(entity, entities[entity])
        files[folder / "intent-layout.md"] = intent_layout_template(entities)
        files[folder / "overall-solution-network.md"] = overall_template(entities)
        files[folder / "repository-standard.md"] = standard_template(rows)
        files[folder / "metric-run-policy.md"] = metric_run_policy_template(entities)
        files[folder / "review-sheet.md"] = review_sheet(rows)
        for name, text in record_headers(rows).items():
            files[folder / "record-headers" / name] = text
    if config.excerpts_file:
        files[config.root / config.excerpts_file] = excerpts(skill_text)
    return files


def sync(config: Config, source: Optional[str] = None, check: bool = False, say: Callable[[str], None] = print) -> int:
    """Write (or with ``check`` only compare) the parsed template and every generated document. Exit codes: 0 ok,
    1 stale, 2 source not found."""
    path = config.template_source_path(source)
    if path is None or not path.exists():
        say(f"template source not found ({path.name if path else 'none configured'}); set template_source in the "
            "config, ESOI_TEMPLATE_SOURCE, or pass --source")
        return 2
    skill_text = path.read_text(encoding="utf-8")
    rows, notes = parse(skill_text)
    for note in notes:
        say(f"note: {note}")
    if not rows:
        say("nothing parsed; refusing to write")
        return 2
    wanted: Dict[Path, str] = {template_csv_path(config): render_template_csv(rows)}
    standard = standard_doc_path(config)
    if standard.exists():
        current = standard.read_text(encoding="utf-8")
        wanted[standard] = apply_section(current, render_section(rows))
    wanted.update(generated_files(rows, skill_text, config))
    stale = [p for p, text in wanted.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if check:
        say("stale: " + ", ".join(str(p.relative_to(config.root)) for p in stale) + " (run `esoi template sync`)"
            if stale else "esoi template ok")
        return 1 if stale else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(wanted[p], encoding="utf-8")
    say(f"wrote {len(stale)} of {len(wanted)} file(s)")
    return 0
