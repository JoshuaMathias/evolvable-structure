def label(key: str) -> str:
    return key.replace("_", " ").capitalize()


def by_entity(rows: List[Dict[str, str]]) -> Dict[str, Dict[str, object]]:
    out: Dict[str, Dict[str, object]] = {}
    for row in rows:
        entry = out.setdefault(row["entity"], {"meta": {}, "specify": [], "interface": []})
        if row["group"] == "meta":
            entry["meta"][row["field_key"]] = row["question"]
        else:
            entry[row["group"]].append(row)
    return out


def entity_template(entity: str, info: Dict[str, object]) -> str:
    meta = info["meta"]
    out = [f"<!-- {ATTRIBUTION} -->", "", f"# {entity.capitalize()} (template)", "",
           f"> {meta.get('definition', '')}", "", "Copy this file once per record. Answer every question; leave none empty. "
           "Give the record a short stable id (a few lowercase words joined by hyphens) so other records can link to it.", "",
           "## Id", "", "<!-- the record's id -->", ""]
    for row in info["specify"]:
        out += [f"## {label(row['field_key'])}", "", f"_{row['question']}_", "", "<!-- your answer -->", ""]
    if info["interface"]:
        out += ["## If the solution is technology: interface (optional)", ""]
        for row in info["interface"]:
            out += [f"### {label(row['field_key'])}", "", f"_{row['question']}_", "", "<!-- your answer -->", ""]
    if "what_it_is_not" in meta:
        out += ["## What it is not", "", str(meta["what_it_is_not"]), ""]
    if "connects_to" in meta:
        out += ["## Connects to", "", str(meta["connects_to"]), ""]
    return "\n".join(out)


def overall_template(entities: Dict[str, Dict[str, object]]) -> str:
    sections = [("problem", "Problems", "P"), ("ideal", "Ideals", "I"), ("solution", "The overall solution and its areas", "S"),
                ("implementation", "Alternatives (implementations of the overall solution)", "A"),
                ("metric", "Top metrics", "M")]
    out = [f"<!-- {ATTRIBUTION} -->", "", "# Overall solution network (template)", "",
           "Every repository writes one overall network: why it exists, what it should become, what it is defined to do, "
           "the alternatives to it, and how to tell whether it succeeds. Everything practical in the repository (each detailed "
           "solution, each module) implements a part of it, and each detailed record links up to it with "
           "`parent_problem_ids`, `parent_ideal_ids`, `overall_solution_ids` or `parent_metric_ids`.", "",
           "Write each item as a heading with the id and a short title, then one bullet per field, in the template's own "
           "words. Keep ids short and stable so records can link to them.", ""]
    for entity, title, prefix in sections:
        info = entities.get(entity)
        if not info:
            continue
        out += [f"## {title}", "", f"### {prefix}1 Short title"]
        for row in info["specify"] + info["interface"]:
            out.append(f"- **{row['question']}** <!-- {label(row['field_key'])} -->")
        if entity == "problem":
            out.append("- **Addressed by:** <!-- solution ids -->  **Opposed by:** <!-- ideal ids -->")
        if entity == "ideal":
            out.append("- **Opposes:** <!-- problem ids -->")
        if entity == "solution":
            out.append("- **Addresses:** <!-- problem ids -->  **Pursues:** <!-- ideal ids -->")
        if entity == "implementation":
            out.append("- **Implements:** <!-- solution id -->")
        if entity == "metric":
            out.append("- **Measures:** <!-- solution ids -->")
        out.append("")
    return "\n".join(out)


