"""A public, self-contained copy of the author's skill, generated from the private skill that is its source of truth.

The author keeps the evolvable-structure skill in a folder that also holds material that is not public. This module
makes the public copy from it, so there is one source of truth and the copy cannot drift:

    esoi skill sync      write the copy (the folders named by ``dir`` and ``copies``) from the source
    esoi skill check     fail when a copy is stale, differs from the other copies, or leaks something private
    esoi skill install   copy the bundled skill into a user's or a project's skills folder (no source, no config)

The ``[skill]`` table of the configuration names only public things:

    dir          the folder of the primary copy, for example ``skill/evolvable-structure``
    copies       further folders that must hold the identical copy (the one bundled in the package)
    include      the files of the source that ship, as globs relative to the source folder
    notice       the generated-file notice, placed in an HTML comment after the frontmatter of SKILL.md
    substitute   a list of ``{file, pattern, replacement, reason}``: a regular expression that must match exactly once
    private_dirs folders of the source that do not ship, so a reference into one is a leak
    source       where the source folder is, when the environment variable does not say

The source folder comes from ``--source``, then ``ESOI_SKILL_SOURCE``, then ``source``. Text between ``<!--private`` and ``-->``
in a source file is removed from the copy (a pointer to a note that does not ship, or a passage for the author's own setting).

The deny list of private terms (people, internal names) is never committed here. It is read from the file named by
``--denylist`` or ``ESOI_SKILL_DENYLIST``: one term per line, ``#`` starts a comment, a line starting ``re:`` is a regular
expression, and matching ignores case. Without it ``check`` still finds the generic leaks: an absolute machine path, an email
address, a leftover private marker, a pointer to a note that does not ship and a reference to a file the copy lacks.
"""
from __future__ import annotations

import os
import re
import shutil
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, Dict, List, Optional, Tuple

from .config import Config

SOURCE_ENV = "ESOI_SKILL_SOURCE"
DENYLIST_ENV = "ESOI_SKILL_DENYLIST"
SKILL_FILE = "SKILL.md"
BUNDLED = Path(__file__).resolve().parent / "data" / "skill"
DEFAULT_NOTICE = ("Generated by `esoi skill sync` from the author's own skill, which is the source of truth. "
                  "Do not edit this copy: a change here is overwritten.")

PRIVATE_SPAN = re.compile(r"[ \t]*<!--private\b.*?-->[ \t]*", re.S)
MARKER_LEFT = re.compile(r"<!--\s*private\b")
ABSOLUTE_PATH = re.compile(r"(?<![\w.~-])/(?:home|Users|root|mnt|opt|var|etc|usr|tmp|srv)/[\w.-]+|\b[A-Za-z]:\\\\?[\w.-]+")
EMAIL = re.compile(r"(?<![\w.+-])[\w][\w.+-]*@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+")
POINTER = re.compile(r"`+([\w-]+\.(?:md|txt))\s*>")
PATH_TOKEN = re.compile(r"`((?:\.\./)*(?:[\w-]+/)+[\w.-]+\.(?:md|txt))`")
FRONTMATTER_END = re.compile(r"\A(---\n.*?\n---\n)", re.S)


class SkillError(ValueError):
    """The skill configuration or the source is not usable."""


@dataclass(frozen=True)
class Substitution:
    """One regular-expression replacement in one included file, with the reason it exists."""
    file: str
    pattern: str
    replacement: str
    reason: str


@dataclass(frozen=True)
class Finding:
    """One leak: where, which kind, and the text that gave it away."""
    path: str
    line: int
    kind: str
    snippet: str

    def __str__(self) -> str:
        return f"{self.path}:{self.line}: {self.kind}: {self.snippet}"


@dataclass
class Settings:
    """The ``[skill]`` table, validated."""
    dir: str
    include: List[str]
    copies: List[str] = field(default_factory=list)
    notice: str = DEFAULT_NOTICE
    substitutions: List[Substitution] = field(default_factory=list)
    private_dirs: List[str] = field(default_factory=list)
    source: str = ""


def settings_from(config: Config) -> Settings:
    table = dict(config.skill)
    if not table:
        raise SkillError("no [skill] table in the configuration")
    unknown = sorted(set(table) - {"dir", "include", "copies", "notice", "substitute", "private_dirs", "source"})
    if unknown:
        raise SkillError(f"unknown [skill] key(s): {', '.join(unknown)}")
    if not table.get("dir") or not table.get("include"):
        raise SkillError("[skill] needs `dir` and `include`")
    substitutions = []
    for entry in table.get("substitute", []):
        missing = {"file", "pattern", "replacement", "reason"} - set(entry)
        if missing:
            raise SkillError(f"a [[skill.substitute]] entry lacks {', '.join(sorted(missing))}")
        substitutions.append(Substitution(entry["file"], entry["pattern"], entry["replacement"], entry["reason"]))
    return Settings(table["dir"], list(table["include"]), list(table.get("copies", [])), table.get("notice", DEFAULT_NOTICE),
                    substitutions, list(table.get("private_dirs", [])), table.get("source", ""))


def source_folder(config: Config, settings: Settings, override: Optional[str] = None) -> Optional[Path]:
    """Where the source skill is: an override, ``$ESOI_SKILL_SOURCE``, then ``source``. A path to its SKILL.md also works."""
    chosen = override or os.environ.get(SOURCE_ENV) or settings.source
    if not chosen:
        return None
    path = Path(chosen).expanduser()
    path = path if path.is_absolute() else config.root / path
    path = path.parent if path.is_file() else path
    return path if (path / SKILL_FILE).is_file() else None


def strip_private(text: str) -> str:
    """Remove every ``<!--private ... -->`` span, with the spaces around it, and the line it leaves empty."""
    out: List[str] = []
    position = 0
    for match in PRIVATE_SPAN.finditer(text):
        start, end = match.start(), match.end()
        rest = text[end:]
        at_line_start = start == 0 or text[start - 1] == "\n"
        ends_line = rest == "" or rest.startswith("\n")
        if at_line_start and ends_line:
            out.append(text[position:start])
            position = end + (1 if rest.startswith("\n") else 0)
        elif at_line_start and re.match(r"[.,;:)]", rest):
            out.append(text[position:start].rstrip(" \t\n"))
            position = end
        elif ends_line or re.match(r"[.,;:)\]]", rest):
            out.append(text[position:start])
            position = end
        else:
            out.append(text[position:start] + " ")
            position = end
    out.append(text[position:])
    return "".join(out)


def apply_substitutions(rel: str, text: str, substitutions: List[Substitution]) -> str:
    for sub in substitutions:
        if sub.file != rel:
            continue
        text, count = re.subn(sub.pattern, sub.replacement, text)
        if count != 1:
            raise SkillError(f"substitution in {rel} matched {count} time(s), not once ({sub.reason}); the source changed, "
                             "so update the [[skill.substitute]] entry")
    return text


def add_notice(text: str, notice: str) -> str:
    """Put the generated-file notice in an HTML comment right after the frontmatter, never in the text."""
    match = FRONTMATTER_END.match(text)
    if not match:
        raise SkillError(f"{SKILL_FILE} has no frontmatter to put the notice after")
    return match.group(1) + f"<!-- {notice} -->\n" + text[match.end():]


def transform(rel: str, text: str, settings: Settings) -> str:
    """One included file as it ships: private spans removed, substitutions applied, the notice added to SKILL.md."""
    text = apply_substitutions(rel, strip_private(text), settings.substitutions)
    return add_notice(text, settings.notice) if rel == SKILL_FILE else text


def included(source: Path, patterns: List[str]) -> List[str]:
    """The source files that ship, as sorted posix paths relative to the source folder."""
    found = set()
    for pattern in patterns:
        matches = [p for p in source.glob(pattern) if p.is_file()]
        if not matches:
            raise SkillError(f"include pattern {pattern!r} matches no file in {source}")
        found.update(p.relative_to(source).as_posix() for p in matches)
    if SKILL_FILE not in found:
        raise SkillError(f"include must contain {SKILL_FILE}")
    return sorted(found)


def build_copy(source: Path, settings: Settings) -> Dict[str, str]:
    """The public copy as {relative path: text}, made from the source folder."""
    return {rel: transform(rel, (source / rel).read_text(encoding="utf-8"), settings) for rel in included(source, settings.include)}


def read_copy(folder: Path) -> Dict[str, str]:
    """The files of a copy on disk as {relative path: text}; an absent folder is an empty copy."""
    if not folder.is_dir():
        return {}
    return {p.relative_to(folder).as_posix(): p.read_text(encoding="utf-8") for p in sorted(folder.rglob("*")) if p.is_file()}


def differences(wanted: Dict[str, str], committed: Dict[str, str]) -> List[str]:
    """Paths that are missing, changed or extra in ``committed`` compared with ``wanted``."""
    out = [f"{rel} (missing)" for rel in wanted if rel not in committed]
    out += [f"{rel} (changed)" for rel in wanted if rel in committed and committed[rel] != wanted[rel]]
    out += [f"{rel} (not in the source)" for rel in committed if rel not in wanted]
    return out


def load_denylist(path: Optional[str]) -> List[Tuple[str, "re.Pattern[str]"]]:
    """The private terms: (the line, its pattern). A missing file is an error, since the caller asked for it."""
    chosen = path or os.environ.get(DENYLIST_ENV)
    if not chosen:
        return []
    file = Path(chosen).expanduser()
    if not file.is_file():
        raise SkillError(f"deny list not found: {file.name}")
    terms = []
    for raw in file.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        pattern = line[3:] if line.startswith("re:") else re.escape(line)
        terms.append((line, re.compile(pattern, re.I)))
    return terms


def resolves(rel: str, token: str, files: Dict[str, str]) -> bool:
    """Whether a path written in a file is a shipped file, from the file's folder or from the skill's root."""
    here = os.path.normpath((Path(rel).parent / token).as_posix())
    return here in files or os.path.normpath(token) in files


def scan(files: Dict[str, str], denylist: List[Tuple[str, "re.Pattern[str]"]] = (), private_dirs: List[str] = ()) -> List[Finding]:
    """Every leak in a copy: generic ones always, deny-list terms when a list is given."""
    names = {rel.rsplit("/", 1)[-1] for rel in files}
    top = {rel.split("/", 1)[0] for rel in files if "/" in rel}
    found: List[Finding] = []
    for rel, text in sorted(files.items()):
        for number, line in enumerate(text.splitlines(), 1):
            for kind, rx in (("absolute-path", ABSOLUTE_PATH), ("email", EMAIL)):
                found.extend(Finding(rel, number, kind, m.group(0)) for m in rx.finditer(line))
            if MARKER_LEFT.search(line):
                found.append(Finding(rel, number, "private-marker", "an unstripped private span"))
            found.extend(Finding(rel, number, "pointer-to-unshipped-note", m.group(1)) for m in POINTER.finditer(line)
                         if m.group(1) not in names)
            for m in PATH_TOKEN.finditer(line):
                first = next(part for part in m.group(1).split("/") if part != "..")
                if first in (*top, *private_dirs) and not resolves(rel, m.group(1), files):
                    found.append(Finding(rel, number, "reference-to-a-file-not-shipped", m.group(1)))
            for term, rx in denylist:
                if rx.search(line):
                    found.append(Finding(rel, number, "denied-term", term))
    return found


def copy_folders(config: Config, settings: Settings) -> List[Path]:
    return [config.root / settings.dir] + [config.root / c for c in settings.copies]


def sync(config: Config, source: Optional[str] = None, check: bool = False, say: Callable[[str], None] = print) -> int:
    """Write (or with ``check`` only compare) every copy. Exit codes: 0 ok, 1 stale, 2 source or settings not usable."""
    try:
        settings = settings_from(config)
        folder = source_folder(config, settings, source)
        if folder is None:
            say("skill source not found; set ESOI_SKILL_SOURCE, pass --source, or set source in the [skill] table")
            return 2
        wanted = build_copy(folder, settings)
    except SkillError as exc:
        say(f"esoi: {exc}")
        return 2
    stale: List[str] = []
    for target in copy_folders(config, settings):
        for line in differences(wanted, read_copy(target)):
            stale.append(f"{target.relative_to(config.root).as_posix()}/{line}")
    if check:
        say("stale: " + "; ".join(stale) + " (run `esoi skill sync`)" if stale else "esoi skill copy is current")
        return 1 if stale else 0
    for target in copy_folders(config, settings):
        if target.is_dir():
            shutil.rmtree(target)
        for rel, text in wanted.items():
            path = target / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    say(f"wrote {len(wanted)} file(s) to {len(copy_folders(config, settings))} folder(s)")
    return 0


def check(config: Config, source: Optional[str] = None, denylist: Optional[str] = None,
          say: Callable[[str], None] = print) -> int:
    """The copy is current (when the source is reachable), the copies agree, and nothing private leaked. Exit 0 ok, 1 not."""
    try:
        settings = settings_from(config)
        terms = load_denylist(denylist)
        folder = source_folder(config, settings, source)
    except SkillError as exc:
        say(f"esoi: {exc}")
        return 2
    primary_dir, *others = copy_folders(config, settings)
    primary = read_copy(primary_dir)
    problems: List[str] = [] if primary else [f"{settings.dir}: no copy yet (run `esoi skill sync`)"]
    problems += [str(f) for f in scan(primary, terms, settings.private_dirs)]
    for other in others:
        problems += [f"{other.relative_to(config.root).as_posix()}/{line} (differs from {settings.dir})"
                     for line in differences(primary, read_copy(other))]
    if folder is None:
        say("note: skill source not reachable, so freshness was not checked; leaks were checked on the committed copy")
    else:
        try:
            wanted = build_copy(folder, settings)
        except SkillError as exc:
            say(f"esoi: {exc}")
            return 2
        problems += [f"{settings.dir}/{line} (stale against the source)" for line in differences(wanted, primary)]
    if not terms:
        say("note: no deny list given, so only the generic leaks were checked")
    for line in problems:
        say(line)
    if not problems:
        say("esoi skill ok")
    return 1 if problems else 0


def target_folder(project: Optional[str], dest: Optional[str], name: str) -> Path:
    """Where the skill goes: ``--dest`` (a skills folder), a project's ``.claude/skills``, else the user's."""
    if dest:
        return Path(dest).expanduser() / name
    if project:
        return Path(project).expanduser() / ".claude" / "skills" / name
    return Path.home() / ".claude" / "skills" / name


def install(project: Optional[str] = None, dest: Optional[str] = None, source: Optional[str] = None, force: bool = False,
            say: Callable[[str], None] = print) -> int:
    """Copy the bundled skill (or the folder given as ``source``) into a skills folder. Exit codes: 0 done, 1 target exists
    with other content (use ``force``), 2 no skill to install."""
    folder = Path(source).expanduser() if source else next((p for p in sorted(BUNDLED.glob("*")) if (p / SKILL_FILE).is_file()), None)
    if folder is None or not (folder / SKILL_FILE).is_file():
        say("no skill to install: the package carries no bundled copy, and no --from folder was given")
        return 2
    target = target_folder(project, dest, folder.name)
    wanted = read_copy(folder)
    if target.exists():
        if read_copy(target) == wanted:
            say(f"already installed and current: {target}")
            return 0
        if not force:
            say(f"{target} exists with other content; pass --force to replace it")
            return 1
        shutil.rmtree(target)
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(folder, target)
    say(f"installed {len(wanted)} file(s) to {target}")
    return 0
