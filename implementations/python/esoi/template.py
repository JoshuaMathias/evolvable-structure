"""Read the intent template from a SKILL.md-style markdown file and keep a parsed copy in step with it.

The evolvable-structure skill's ``SKILL.md`` holds the "Intent template definitions": for each of Problem,
Solution, Implementation, Ideal and Metric, a definition, a ``Specify:`` list of fields, for a technology
solution an interface list, "What it's not" and "Connects to". The author refines that text, so it is read
here instead of being copied. The parsed form is ``esoi_template.csv`` with the columns
``entity, field_key, question, group, required``; groups are ``specify`` (a required column of that entity's
records), ``interface`` (optional, for a solution that is technology) and ``meta`` (the definition, "What it's
not" and "Connects to" text, not a column).

Field keys are snake_case of the label (``Scoped Purpose`` -> ``scoped_purpose``). A bare question has no label,
so ``BARE_KEYS`` maps each to a short stable key by the words that identify it; refining the wording of a
question keeps its key as long as those words stay. An unmapped bare question gets a key from its first words
and is reported.

The parser is tolerant: an empty ``- `` bullet (an unfinished section) is skipped and counted, bullets and
indentation may vary, and a missing section is reported, not fatal. A repository without the skill uses the copy
shipped in ``esoi/data/esoi_template.csv``.
"""
from __future__ import annotations

import re
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from .config import Config
from .tables import render_csv

ENTITIES = ["problem", "solution", "implementation", "ideal", "metric"]
COLUMNS = ["entity", "field_key", "question", "group", "required"]
START = "<!-- esoi-template:start (generated by `esoi template sync`; do not edit) -->"
END = "<!-- esoi-template:end -->"
MARKER = re.compile(r"<!-- esoi-template:start[^>]*-->")

# (entity, regex on the lowercased question, key). First match wins. Keep these as keywords of the idea,
# not of the wording, so refining a question does not rename its column.
BARE_KEYS = [
    ("problem", r"what is the problem", "problem"),
    ("problem", r"\bwho\b", "who_has_it"),
    ("problem", r"\bmatter", "why_it_matters"),
    ("problem", r"\bhard\b|difficult", "why_hard"),
    ("problem", r"workaround|already attempt|existing", "existing_attempts"),
    ("solution", r"when and how|other information", "usage_notes"),
    ("solution", r"effects", "effects"),
]
HEADER = re.compile(r"^(specify|if technology[^:]*|what it'?s not|connects to)\s*:\s*(.*)$", re.I)
ITEM = re.compile(r"^-\s+\*\*(\w[\w ]*)\*\*\s*:\s*(.*)$")
LABELLED = re.compile(r"^([A-Z][A-Za-z]*(?: [A-Za-z]+){0,3}):\s*(.*)$")


def snake(text: str) -> str:
    text = re.sub(r"\([^)]*\)", " ", text)
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def clean(text: str) -> str:
    return re.sub(r"\s+", " ", text.replace("**", "")).strip()


def template_lines(skill_text: str) -> List[str]:
    """The lines of the intent template block: from its heading line to the first unindented line that is
    neither an item nor blank (or the next ``#`` heading)."""
    lines = skill_text.splitlines()
    start = next((i for i, line in enumerate(lines) if line.lower().startswith("intent template definitions")), None)
    if start is None:
        return []
    block = []
    for line in lines[start + 1:]:
        if line.startswith("#"):
            break
        if line.strip() and not line.startswith((" ", "\t")) and not ITEM.match(line):
            break
        block.append(line)
    return block


def field_key(entity: str, text: str) -> Tuple[str, str, bool]:
    """(key, question, mapped) for one field line with its bullet removed."""
    labelled = LABELLED.match(text)
    if labelled and "?" not in labelled.group(1):
        return snake(labelled.group(1)), clean(labelled.group(2)) or clean(labelled.group(1)), True
    lowered = text.lower()
    for ent, pattern, key in BARE_KEYS:
        if ent == entity and re.search(pattern, lowered):
            return key, clean(text), True
    if "?" not in text and len(snake(text).split("_")) <= 3:
        return snake(text), clean(text), True            # a bare label such as Parameters or Advantages
    skip = {"what", "is", "the", "a", "an", "of", "does", "do", "how", "would"}
    words = [w for w in snake(text).split("_") if w not in skip]
    return "_".join(words[:3]) or "field", clean(text), False


def parse(skill_text: str) -> Tuple[List[Dict[str, str]], List[str]]:
    """The template rows and a list of notes about what was parsed, skipped or guessed."""
    notes: List[str] = []
    rows: List[Dict[str, str]] = []
    block = template_lines(skill_text)
    if not block:
        return rows, ["no 'Intent template definitions' block found"]
    items: List[dict] = []
    current: Optional[dict] = None
    section = ""
    for raw in block:
        if not raw.strip():
            continue
        line = raw.strip()
        item = ITEM.match(line) if not raw.startswith((" ", "\t")) else None
        if item:
            current = {"entity": item.group(1).strip().lower(), "definition": item.group(2).strip(),
                       "specify": [], "interface": [], "not": [], "connects": [], "empty": 0}
            items.append(current)
            section = "definition"
            continue
        if current is None:
            continue
        stripped = re.sub(r"^-\s*", "", line)
        header = HEADER.match(stripped)
        if header:
            name = header.group(1).lower()
            section = "specify" if name == "specify" else "interface" if name.startswith("if technology") else \
                "not" if name.startswith("what") else "connects"
            if header.group(2).strip() and section in ("not", "connects"):
                current[section].append(header.group(2).strip())
            continue
        if line in ("-", ""):
            current["empty"] += 1
            continue
        if section in ("specify", "interface", "not", "connects"):
            current[section].append(stripped)
        elif section == "definition":
            current["definition"] += " " + stripped
    seen = {i["entity"] for i in items}
    for missing in [e for e in ENTITIES if e not in seen]:
        notes.append(f"{missing}: section missing from the source")
    for item in items:
        entity = item["entity"]
        rows.append({"entity": entity, "field_key": "definition", "question": clean(item["definition"]),
                     "group": "meta", "required": "no"})
        keys: set = set()
        for group in ("specify", "interface"):
            for text in item[group]:
                key, question, mapped = field_key(entity, text)
                if key in keys:
                    notes.append(f"{entity}: duplicate key {key!r} skipped")
                    continue
                keys.add(key)
                if not mapped:
                    notes.append(f"{entity}: bare question {question!r} has no entry in BARE_KEYS; key {key!r} guessed")
                rows.append({"entity": entity, "field_key": key, "question": question, "group": group,
                             "required": "yes" if group == "specify" else "no"})
        for name, key in (("not", "what_it_is_not"), ("connects", "connects_to")):
            if item[name]:
                rows.append({"entity": entity, "field_key": key, "question": clean(" ".join(item[name])),
                             "group": "meta", "required": "no"})
        if item["empty"]:
            notes.append(f"{entity}: {item['empty']} empty bullet(s) skipped (section unfinished)")
        required = [r for r in rows if r["entity"] == entity and r["group"] == "specify"]
        optional = [r for r in rows if r["entity"] == entity and r["group"] == "interface"]
        notes.append(f"{entity}: {len(required)} required field(s), {len(optional)} interface field(s)")
    return rows, notes


def render_template_csv(rows: List[Dict[str, str]]) -> str:
    return render_csv(COLUMNS, rows)


def render_section(rows: List[Dict[str, str]]) -> str:
    """The generated standard-document section: one table per entity of the fields its records carry."""
    out = [START, "", "Generated from the intent template by `esoi template sync`; the records in the structure",
           "folder carry exactly these columns (a `Specify:` field is required, an interface field is optional and",
           "meant for a solution that is technology).", ""]
    for entity in ENTITIES:
        mine = [r for r in rows if r["entity"] == entity]
        if not mine:
            continue
        meta = {r["field_key"]: r["question"] for r in mine if r["group"] == "meta"}
        out.append(f"**{entity.capitalize()}**: {meta.get('definition', '')}")
        out.append("")
        out.append("| Column | Required | Question |")
        out.append("|---|---|---|")
        for r in mine:
            if r["group"] != "meta":
                out.append(f"| `{r['field_key']}` | {r['required']} | {r['question'].replace('|', '/')} |")
        for key, label in (("what_it_is_not", "What it is not"), ("connects_to", "Connects to")):
            if key in meta:
                out.append("")
                out.append(f"{label}: {meta[key]}")
        out.append("")
    out.append(END)
    return "\n".join(out)


def apply_section(document: str, section: str) -> str:
    """Replace the generated section of a document; a document without the markers is returned unchanged."""
    if MARKER.search(document) and END in document:
        head = MARKER.split(document, 1)[0]
        return head + section + document.split(END, 1)[1]
    return document


def template_csv_path(config: Config) -> Path:
    return config.structure / (config.template_csv or "esoi_template.csv")


def standard_doc_path(config: Config) -> Path:
    return config.structure / "STANDARD.md"


def load_for(config: Config) -> Dict[str, List[Dict[str, str]]]:
    """The template this repository's records are checked against: its own parsed copy, else the shipped one."""
    from .records import load_template
    own = template_csv_path(config)
    return load_template(own if own.exists() else None)


def stale_against_source(config: Config) -> Optional[bool]:
    """Whether the committed parsed copy differs from the source; ``None`` when the source cannot be read here."""
    path = config.template_source_path()
    own = template_csv_path(config)
    if path is None or not path.exists() or not own.exists():
        return None
    rows, _ = parse(path.read_text(encoding="utf-8"))
    return render_template_csv(rows) != own.read_text(encoding="utf-8")
